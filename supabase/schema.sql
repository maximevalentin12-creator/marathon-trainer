-- ─── Garmin Connect auth session (one row per user) ───────────────────────────
-- Persists the garminconnect library's session (mobile SSO / DI OAuth Bearer
-- tokens — di_token/di_refresh_token/di_client_id, see client.dumps() in the
-- installed garminconnect package) so scripts/sync_garmin.py can resume a
-- session instead of logging in with credentials on every run. Deliberately in
-- Supabase, not a local file: the app deploys to Vercel, whose filesystem is
-- ephemeral, and a file-based token store would force a fresh credential login
-- (and its 4-5 SSO strategy attempts) on every cold start.
CREATE TABLE garmin_tokens (
  user_id        UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  -- Nullable: a cooldown can be recorded (see below) before any login has ever
  -- succeeded, e.g. the very first --login attempt gets rate-limited.
  token_payload  JSONB,
  -- Set when a Garmin rate limit (HTTP 429) or Cloudflare challenge is hit;
  -- sync_garmin.py refuses every further Garmin call for this user until this
  -- timestamp passes, and clears it on the next successful login. Retrying
  -- during a block is what extends it — see is_rate_limited() in the script.
  cooldown_until TIMESTAMPTZ,
  created_at     TIMESTAMPTZ DEFAULT NOW(),
  updated_at     TIMESTAMPTZ DEFAULT NOW()
);

CREATE TRIGGER garmin_tokens_set_updated_at
  BEFORE UPDATE ON garmin_tokens
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

