-- Marathon Trainer — Supabase schema
-- Run this once in the Supabase SQL editor.

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ─── Users ───────────────────────────────────────────────────────────────────

CREATE TABLE users (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email               TEXT UNIQUE NOT NULL,
  garmin_username     TEXT,
  -- Optional: the app is continuous/quarterly (spec Prompt 6 §6), not race-anchored.
  race_date           DATE,
  current_weekly_km   FLOAT    DEFAULT 30,
  -- Initial suggestion only — the live default lives in progression_state.suggested_runs_per_week,
  -- and the weekly setup panel always has the final say (weekly_setups).
  runs_per_week       SMALLINT DEFAULT 2  CHECK (runs_per_week BETWEEN 1 AND 3),
  pb_5k_seconds       INTEGER,
  pb_10k_seconds      INTEGER,
  pb_half_seconds     INTEGER,
  pb_marathon_seconds INTEGER,
  injury_history      TEXT,
  -- Athlete profile: every HR zone is derived from these (lib/planner/zones.ts).
  -- Source: garmin_settings | field_test (set in /profil, wins over
  -- garmin_settings) | observed (only ever raises hr_max, after a sync).
  hr_max              SMALLINT NOT NULL DEFAULT 208 CHECK (hr_max BETWEEN 140 AND 230),
  hr_max_source       TEXT     NOT NULL DEFAULT 'garmin_settings'
                      CHECK (hr_max_source IN ('garmin_settings', 'field_test', 'observed')),
  hr_max_updated_at   TIMESTAMPTZ,
  hr_rest             SMALLINT NOT NULL DEFAULT 67 CHECK (hr_rest BETWEEN 30 AND 100),
  hr_rest_source      TEXT     NOT NULL DEFAULT 'garmin_settings'
                      CHECK (hr_rest_source IN ('garmin_settings', 'field_test', 'observed')),
  created_at          TIMESTAMPTZ DEFAULT NOW(),
  updated_at          TIMESTAMPTZ DEFAULT NOW()
);

-- ─── Garmin activities (raw import) ──────────────────────────────────────────

CREATE TABLE garmin_activities (
  id                   UUID    PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id              UUID    REFERENCES users(id) ON DELETE CASCADE,
  garmin_activity_id   BIGINT  UNIQUE NOT NULL,
  activity_type        TEXT,
  start_time           TIMESTAMPTZ,
  duration_seconds     INTEGER,
  distance_meters      FLOAT,
  avg_pace_sec_per_km  FLOAT,
  avg_heart_rate       INTEGER,
  max_heart_rate       INTEGER,
  elevation_gain_m     FLOAT,
  vo2max_estimate      FLOAT,
  avg_cadence              INTEGER,
  max_cadence              INTEGER,
  avg_ground_contact_ms    INTEGER,
  avg_vertical_oscillation FLOAT,
  avg_stride_length        FLOAT,
  aerobic_te               FLOAT,
  best_pace_sec_per_km     INTEGER,
  total_ascent_m           INTEGER,
  gap_pace_sec_per_km      INTEGER,
  -- Per-lap splits [{index, durationSeconds, distanceMeters, avgHr, maxHr,
  -- avgPaceSecPerKm, intensityType}] — fetched by sync_garmin.py --fetch-laps
  -- only for activities matched to (non-fartlek) quality sessions, to score
  -- their work reps (lib/planner/completion.ts). NULL = not fetched yet.
  laps                     JSONB,
  raw_data             JSONB,
  created_at           TIMESTAMPTZ DEFAULT NOW(),
  -- One row per activity: the CSV import updates the row at an existing
  -- start_time instead of inserting (see app/api/import/csv/route.ts).
  CONSTRAINT garmin_activities_user_start_time_key UNIQUE (user_id, start_time)
);

CREATE INDEX garmin_activities_user_id_idx   ON garmin_activities(user_id);
CREATE INDEX garmin_activities_start_time_idx ON garmin_activities(start_time DESC);

-- ─── Shoes ("L'armoire" — shoe rotation) ──────────────────────────────────────

CREATE TABLE shoes (
  id                UUID    PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id           UUID    REFERENCES users(id) ON DELETE CASCADE,
  name              TEXT    NOT NULL,
  brand             TEXT,
  model             TEXT,
  drop_mm           FLOAT,
  stack_heel_mm     FLOAT,
  stack_forefoot_mm FLOAT,
  weight_g          INTEGER,
  -- Free-form, e.g. "daily/long run", "treadmill", "tempo/performance".
  usage_type        TEXT,
  -- Either a pasted image URL or a Supabase Storage public URL — see /shoes.
  image_url         TEXT,
  notes             TEXT,
  -- Sum of the actual distance (km) of every planned_sessions row linked to
  -- this shoe (see PATCH /api/plan/session's "setShoe" action) — not a live
  -- aggregate, so it stays correct across shoe deletions/relinks.
  total_km          FLOAT   NOT NULL DEFAULT 0,
  retired           BOOLEAN NOT NULL DEFAULT FALSE,
  created_at        TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX shoes_user_id_idx ON shoes(user_id);

-- ─── Planned sessions (generated by planner) ─────────────────────────────────

CREATE TABLE planned_sessions (
  id                          UUID    PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id                     UUID    REFERENCES users(id) ON DELETE CASCADE,
  planned_date                DATE    NOT NULL,
  -- 'race' = the race itself, planned by race mode (lib/planner/race.ts); matched, never scored.
  session_type                TEXT    NOT NULL CHECK (session_type IN ('easy', 'long', 'threshold', 'vo2max', 'rest', 'race')),
  -- Human label shown in the UI/calendar, e.g. "Qualité : Fartlek soutenu".
  session_label               TEXT,
  -- Variant pool (Prompt 6 spec §4bis): classic/fartlek (threshold), classic/hills (vo2max),
  -- continuous/progression (long), plain (easy/rest).
  variant                     TEXT,
  indoor                      BOOLEAN DEFAULT FALSE,
  incline_percent             FLOAT,
  -- Array of {label, durationMinutes, description, zoneLabel, paceHint?, heartRateHint?} — see lib/planner/types.ts.
  steps                       JSONB,
  zone_summary                TEXT,
  downgraded_from             TEXT,
  downgrade_reason            TEXT,
  strides_added                BOOLEAN DEFAULT FALSE,
  target_distance_km          FLOAT,
  target_duration_minutes     INTEGER,
  target_pace_sec_per_km      FLOAT,
  why_note                    TEXT,
  google_calendar_event_id    TEXT,
  -- Hash of the fields last pushed to / pulled from Google Calendar.
  -- Used to decide whether a sync round-trip is needed, instead of
  -- racing on updated_at (which a trigger bumps on every write and
  -- would otherwise cause push <-> webhook sync loops).
  google_calendar_payload_hash TEXT,
  google_calendar_synced_at   TIMESTAMPTZ,
  completed                   BOOLEAN DEFAULT FALSE,
  completed_at                TIMESTAMPTZ,
  -- User-marked "didn't happen" (checkbox on the session card). Mutually
  -- exclusive with completed — see the CHECK constraint below.
  skipped                     BOOLEAN NOT NULL DEFAULT FALSE,
  -- Garmin's own activity id (garmin_activities.garmin_activity_id), set by the
  -- sync → session matcher (Prompt 8 spec) once a Garmin activity is linked.
  garmin_activity_id          BIGINT  REFERENCES garmin_activities(garmin_activity_id) ON UPDATE CASCADE,
  -- Position of this session within its week's architecture array (see
  -- weekArchitecture() in lib/planner/rules.ts) — used to re-match a session
  -- across a week regeneration so a manual day override can be carried
  -- forward. Not meaningful across different weeks.
  slot_index                  SMALLINT,
  -- True when planned_date was set by the user (via PATCH /api/plan/session)
  -- rather than by the auto-placement algorithm; regenerating the week keeps
  -- these in place instead of recomputing them.
  manual_day_override          BOOLEAN NOT NULL DEFAULT FALSE,
  created_at                  TIMESTAMPTZ DEFAULT NOW(),
  updated_at                  TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT planned_sessions_no_completed_and_skipped CHECK (NOT (completed AND skipped))
);

CREATE INDEX planned_sessions_user_date_idx ON planned_sessions(user_id, planned_date);
CREATE INDEX planned_sessions_gcal_event_idx ON planned_sessions(google_calendar_event_id);
CREATE INDEX planned_sessions_garmin_activity_idx ON planned_sessions(garmin_activity_id);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER planned_sessions_set_updated_at
  BEFORE UPDATE ON planned_sessions
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ─── Subjective entries (mood / injury / strain) ──────────────────────────────

CREATE TABLE subjective_entries (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id        UUID REFERENCES users(id) ON DELETE CASCADE,
  session_id     UUID REFERENCES planned_sessions(id),
  entry_date     DATE NOT NULL,
  mood_score     SMALLINT CHECK (mood_score BETWEEN 1 AND 5),
  energy_score   SMALLINT CHECK (energy_score BETWEEN 1 AND 5),
  pain_score     SMALLINT CHECK (pain_score BETWEEN 0 AND 5),
  injury_notes   TEXT,
  strain_notes   TEXT,
  overall_notes  TEXT,
  created_at     TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX subjective_entries_user_date_idx ON subjective_entries(user_id, entry_date);

-- ─── Weekly setup (chosen by the user before each week, spec Prompt 6 §4) ─────

CREATE TABLE weekly_setups (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id        UUID REFERENCES users(id) ON DELETE CASCADE,
  week_start     DATE NOT NULL, -- Monday
  -- Running session count. runs_per_week + non_impact_sessions is the week's total, 1-4.
  runs_per_week  SMALLINT NOT NULL CHECK (runs_per_week BETWEEN 0 AND 4),
  indoor_runs    SMALLINT NOT NULL DEFAULT 0 CHECK (indoor_runs BETWEEN 0 AND 4),
  -- Non-impact (vélo d'appartement / assault bike / élliptique) session count —
  -- an alternative modality to running, same physiological roles, no impact.
  non_impact_sessions SMALLINT NOT NULL DEFAULT 0 CHECK (non_impact_sessions BETWEEN 0 AND 4),
  -- Subset of 'bike'/'assault_bike'/'elliptical' the user has access to.
  non_impact_machines TEXT[] NOT NULL DEFAULT '{}',
  -- Subset of 'mon'/'tue'/'wed'/'thu'/'fri'/'sat'/'sun' the user is available
  -- to train on this week; must contain at least (runs_per_week + non_impact_sessions) entries.
  available_days TEXT[] NOT NULL DEFAULT ARRAY['mon','tue','wed','thu','fri','sat','sun'],
  created_at     TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (user_id, week_start),
  CONSTRAINT weekly_setups_total_sessions_check CHECK (runs_per_week + non_impact_sessions BETWEEN 1 AND 4)
);

-- ─── Progression state (one row per user, spec Prompt 6 §3) ───────────────────

CREATE TABLE progression_state (
  user_id                  UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  cycle_start_date         DATE NOT NULL,     -- fixed once; drives Seuil/VO2max week-parity rotation only
  phase                    TEXT NOT NULL DEFAULT 'base' CHECK (phase IN ('base', 'developpement', 'specifique', 'decharge')),
  block_start_date         DATE NOT NULL,     -- Monday the current phase-block began
  quality_level            SMALLINT NOT NULL DEFAULT 0 CHECK (quality_level BETWEEN 0 AND 6),
  suggested_runs_per_week  SMALLINT NOT NULL DEFAULT 2 CHECK (suggested_runs_per_week BETWEEN 1 AND 3),
  last_change_applied      TEXT CHECK (last_change_applied IN ('frequency', 'quality', 'long_run')),
  -- Prescribed long run (min); easy runs derive from it. Moves only through the
  -- progression engine (priority 3), never straight from the live anchor.
  -- NULL until the first week generation, which seeds it from the anchor.
  long_run_minutes          SMALLINT CHECK (long_run_minutes BETWEEN 20 AND 300),
  previous_long_run_minutes SMALLINT, -- value before the last priority-3 step, for rollback
  updated_at               TIMESTAMPTZ DEFAULT NOW()
);

