-- sync_garmin.py replaces a CSV-synthetic activity with its native Garmin copy
-- by re-keying the row's garmin_activity_id; ON UPDATE CASCADE repoints
-- planned_sessions in the same statement. Drops whatever FK(s) currently
-- cover the column (the name may differ between databases) and re-adds one.
DO $$
DECLARE fk record;
BEGIN
  FOR fk IN
    SELECT c.conname
    FROM pg_constraint c
    JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
    WHERE c.conrelid = 'planned_sessions'::regclass
      AND c.contype = 'f'
      AND a.attname = 'garmin_activity_id'
  LOOP
    EXECUTE format('ALTER TABLE planned_sessions DROP CONSTRAINT %I', fk.conname);
  END LOOP;
  ALTER TABLE planned_sessions
    ADD CONSTRAINT planned_sessions_garmin_activity_id_fkey
    FOREIGN KEY (garmin_activity_id) REFERENCES garmin_activities(garmin_activity_id) ON UPDATE CASCADE;
END $$;

